#!/usr/bin/env python3
"""Compile the shared JSON style defaults into a header for native generators."""
import argparse
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def compile_style(profile):
    if profile.get('schema_version') != 1:
        raise ValueError('unsupported generation-style schema')
    if profile['default_projection'] not in ('cahill-keyes', 'authagraph', 'dymaxion', 'myriahedral', 'star-x', 'voronoi'):
        raise ValueError('unsupported default projection')
    for family in ('fiber', 'water', 'coastline', 'resources', 'atmosphere', 'cdn', 'swarm'):
        for key, value in profile[family].items():
            if 'opacity' in key and (type(value) not in (int, float) or not 0 <= value <= 1):
                raise ValueError(f'{family}.{key} must be in [0, 1]')
    if type(profile['swarm']['location_label_outline']) is not bool:
        raise ValueError('swarm.location_label_outline must be a boolean')
    for family, key, minimum in (('coral', 'display_cell_cap', 4), ('cdn', 'record_cap', 1), ('cdn', 'maximum_labels_per_vendor', 0)):
        if type(profile[family][key]) is not int or profile[family][key] < minimum:
            raise ValueError(f'{family}.{key} must be an integer >= {minimum}')
    for family, key, count in (('temperature', 'high_colors', 6), ('atmosphere', 'cloud_colors', 6),
                                ('resources', 'solar_colors', 6), ('coral', 'colors', 4)):
        if len(profile[family][key]) != count:
            raise ValueError(f'{family}.{key} must contain {count} colours')
    palettes = profile['resources']['metric_palettes']
    if any(len(colors) != 5 for colors in palettes.values()):
        raise ValueError('each resource metric requires five colours')
    resource_colors = sum(palettes.values(), []) + profile['resources']['solar_colors'] + profile['coral']['colors']
    if len(set(resource_colors)) != len(resource_colors):
        raise ValueError('resource metrics must not reuse colours')
    lines = ['// Generated by scripts/compile-generation-style.py; edit generation-style.json.',
             '#ifndef CARTOFREAKO_GENERATION_STYLE_H', '#define CARTOFREAKO_GENERATION_STYLE_H',
             '#include <array>', '#include <cstdint>', '#include <izzi-svg.h>',
             'namespace cart0freak0::generation_style {']
    def number(name, value):
        if type(value) not in (int, float) or not math.isfinite(value) or not 0 <= value < 1000000:
            raise ValueError(f'invalid style number: {name}')
        if (name.endswith(('_in', '_pt')) and value <= 0):
            raise ValueError(f'style dimensions must be positive: {name}')
        lines.append(f'inline constexpr double {name} = {float(value)!r};')
    def colors(name, values):
        result = []
        for value in values:
            if re.fullmatch(r'#[0-9a-fA-F]{6}', value):
                result.append('svg::color_qi {' + ', '.join(str(int(value[i:i+2], 16)) for i in (1,3,5)) + '}')
            elif re.fullmatch(r'[a-z][a-z0-9_]*', value): result.append('svg::color::' + value)
            else: raise ValueError(f'invalid style colour: {value}')
        lines.append(f'inline constexpr std::array<svg::color_qi, {len(values)}> {name} {{' + ', '.join(result) + '};')
    for family in ['fiber', 'water', 'coastline', 'coral', 'cdn', 'atmosphere']:
        for key, value in profile[family].items():
            if isinstance(value, (int, float)): number(family + '_' + key, value)
    number('resources_fill_opacity', profile['resources']['fill_opacity'])
    number('swarm_fill_opacity', profile['swarm']['fill_opacity'])
    colors('fiber_terrestrial_colors', [profile['fiber']['terrestrial_color']])
    colors('temperature_high_colors', profile['temperature']['high_colors'])
    colors('cloud_colors', profile['atmosphere']['cloud_colors'])
    colors('solar_colors', profile['resources']['solar_colors'])
    colors('coral_colors', profile['coral']['colors'])
    for key, value in profile['resources']['metric_palettes'].items():
        colors('palette_' + key.replace('-', '_'), value)
    solar = profile['resources']['solar_upper_mw']
    if len(solar) != 5 or any(type(v) not in (int, float) or not math.isfinite(v) or v <= 0 for v in solar) or solar != sorted(set(solar)):
        raise ValueError('solar bounds must be five increasing positive numbers')
    lines.append('inline constexpr std::array<double, 5> solar_upper_mw {' + ', '.join(str(float(v)) for v in solar) + '};')
    bounds = profile['temperature']['high_upper_days']
    if len(bounds) != 5 or any(type(v) is not int or v < 1 for v in bounds) or bounds != sorted(set(bounds)):
        raise ValueError('daily-high bounds must be five increasing positive integers')
    lines.append('inline constexpr std::array<std::uint64_t, 5> temperature_high_upper_days {' + ', '.join(map(str,bounds)) + '};')
    lines += ['}', '#endif', '']
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = ROOT / 'generation-style.json'
    header = ROOT / 'src.generate/generation-style.h'
    content = compile_style(json.loads(source.read_text()))
    if args.check:
        if not header.exists() or header.read_text() != content:
            raise SystemExit('Generation style header is stale; run scripts/compile-generation-style.py')
    elif not header.exists() or header.read_text() != content:
        header.write_text(content)
    print('Generation style defaults verified' if args.check else 'Generation style defaults compiled')

if __name__ == '__main__': main()
